"""Date & time, notifications, footer and theme menus for the deck settings app."""
import glob
import json
import os
import re
import subprocess
import time

from rich.text import Text
from textual.widgets.option_list import Option

HOME = os.path.expanduser("~")
CFG = f"{HOME}/.config/deck"
FLAGS = f"{CFG}/flags"
PREFS = f"{CFG}/prefs.json"
FOOTER_HIDE = f"{CFG}/footer-hide"
ACCENT_TMUX = f"{CFG}/accent.tmux"
TMUX_CONF = f"{HOME}/.tmux.conf"
FOOT_INI = f"{HOME}/.config/foot/foot.ini"
NOTIFY_LOG = os.environ.get("XDG_STATE_HOME", f"{HOME}/.local/state") + "/deck/notify.log"

PURPLE, PINK, CYAN, GREEN = "#bd93f9", "#ff79c6", "#8be9fd", "#50fa7b"
ORANGE, YELLOW, RED, GRAY, FG = "#ffb86c", "#f1fa8c", "#ff5555", "#6272a4", "#f8f8f2"
DOT = "\u25cf "

ACCENTS = [("Purple", PURPLE), ("Pink", PINK), ("Cyan", CYAN), ("Green", GREEN),
           ("Orange", ORANGE), ("Yellow", YELLOW), ("Red", RED)]
FOOTER_BLOCKS = [("cal", "\uf073", "Calendar", "next appointment"), ("ip", "\uf0e8", "IP address", ""),
                 ("cpu", "\uf2db", "CPU", "usage and temperature"), ("mem", "\U000f035b", "Memory", ""),
                 ("disk", "\uf0a0", "Disk", ""), ("up", "\uf017", "Uptime", ""), ("weather", "\uf0c2", "Weather", ""),
                 ("bat", "\uf240", "Battery", "INA228, hidden until connected")]
NOTIFY_FLAGS = [("no-banners", "\uf0f3", "Banners", "alerts in the header"),
                ("no-sounds", "\uf028", "Sounds", "alert sounds"),
                ("no-long-alerts", "\uf254", "Long command alerts", "commands over 30 seconds")]


# ---------- helpers ----------
def sh(cmd: str) -> str:
    return subprocess.run(cmd, shell=True, capture_output=True, text=True).stdout.strip()


def run(args):
    p = subprocess.run(args, capture_output=True, text=True)
    return p.returncode == 0, (p.stdout + " " + p.stderr).strip()


def item(oid, icon, label, desc="", color=PURPLE, disabled=False):
    return Option(Text.assemble((icon, color), "  ", (f"{label:<18}", f"bold {FG}"), (desc, GRAY)),
                  id=oid, disabled=disabled)


def heading(text):
    return Option(Text(text, style=f"bold {GRAY}"), disabled=True)


def onoff(on, extra=""):
    return ("on" if on else "off") + (f"   {extra}" if extra else "")


def swaymsg_exit():
    env = os.environ.copy()
    socks = sorted(glob.glob(f"/run/user/{os.getuid()}/sway-ipc.*.sock"), key=os.path.getmtime)
    if socks:
        env["SWAYSOCK"] = socks[-1]
    subprocess.run(["swaymsg", "exit"], env=env, capture_output=True)


# ---------- stored settings ----------
def load_prefs():
    try:
        return json.load(open(PREFS))
    except Exception:
        return {}


def save_prefs(p):
    os.makedirs(CFG, exist_ok=True)
    json.dump(p, open(PREFS, "w"), indent=2)


def current_accent():
    return load_prefs().get("accent", PURPLE)


def flag(name):
    return os.path.exists(f"{FLAGS}/{name}")


def set_flag(name, on):
    os.makedirs(FLAGS, exist_ok=True)
    path = f"{FLAGS}/{name}"
    if on:
        open(path, "w").close()
    elif os.path.exists(path):
        os.remove(path)


def footer_hidden():
    try:
        return {line.strip() for line in open(FOOTER_HIDE) if line.strip()}
    except FileNotFoundError:
        return set()


def save_footer_hidden(names):
    os.makedirs(CFG, exist_ok=True)
    open(FOOTER_HIDE, "w").write("".join(f"{n}\n" for n in sorted(names)))


def footer_shown():
    return sh("tmux show -gv pane-border-status") == "bottom"


def tmux_conf_set(pattern, line):
    """Replace a line in ~/.tmux.conf, or insert it before the plugin manager's run line."""
    text = open(TMUX_CONF).read()
    if re.search(pattern, text, flags=re.M):
        text = re.sub(pattern, line, text, count=1, flags=re.M)
    else:
        text = re.sub(r"^run '~/.tmux/plugins/tpm/tpm'", line + "\nrun '~/.tmux/plugins/tpm/tpm'", text, count=1, flags=re.M)
    open(TMUX_CONF, "w").write(text)


# ---------- time ----------
def tz():
    return sh("timedatectl show -p Timezone --value") or "unknown"


def ntp_on():
    return sh("timedatectl show -p NTP --value") == "yes"


def ntp_synced():
    return sh("timedatectl show -p NTPSynchronized --value") == "yes"


def military():
    try:
        return bool(re.search(r"^set -g @dracula-military-time\s+['\"]?true", open(TMUX_CONF).read(), flags=re.M))
    except FileNotFoundError:
        return False


# ---------- theme ----------
def write_accent_tmux(a):
    g, d, sep = "#44475a", "#282a36", "\ue0b0"
    os.makedirs(CFG, exist_ok=True)
    open(ACCENT_TMUX, "w").write(
        "# Generated by deck settings: accent color\n"
        f'set -g window-status-current-format "#[fg={g},bg={a}]{sep}#[fg={d},bg={a},bold] #I #W #[fg={a},bg={g}]{sep}"\n'
        f'set -g message-style "bg={a},fg={d}"\n'
        f'set -g mode-style "bg={a},fg={d}"\n')
    text = open(TMUX_CONF).read()
    if "accent.tmux" not in text:
        open(TMUX_CONF, "a").write("\n# Accent color from deck settings (must stay last)\nsource-file -q ~/.config/deck/accent.tmux\n")
    sh(f"tmux source-file {TMUX_CONF}")


def set_foot_cursor(a):
    if not os.path.exists(FOOT_INI):
        return
    text = re.sub(r"^color=[0-9a-fA-F]{6} [0-9a-fA-F]{6}\n", "", open(FOOT_INI).read(), flags=re.M)
    line = f"color=282a36 {a.lstrip('#')}\n"
    if re.search(r"^\[cursor\]\s*$", text, flags=re.M):
        text = re.sub(r"^\[cursor\]\s*\n", "[cursor]\n" + line, text, count=1, flags=re.M)
    else:
        text = text.rstrip("\n") + "\n\n[cursor]\n" + line
    open(FOOT_INI, "w").write(text)


# ---------- menus ----------
class PrefsMixin:
    """Mixed into the Settings app, which provides MenuCls."""

    def prefs_main_items(self):
        hidden = footer_hidden()
        shown = sum(1 for b in FOOTER_BLOCKS if b[0] not in hidden)
        acc = current_accent()
        name = next((n for n, c in ACCENTS if c == acc), "custom")
        return [
            item("datetime", "\uf017", "Date & time", f"{tz()}, {'24' if military() else '12'}-hour", CYAN),
            item("notify", "\uf0f3", "Notifications", "banners " + ("off" if flag("no-banners") else "on"), PINK),
            item("footer", "\uf0db", "Footer",
                 f"{shown} of {len(FOOTER_BLOCKS)} blocks" if footer_shown() else "hidden", GREEN),
            item("theme", "\U000f03d8", "Theme", f"{name} accent", acc),
        ]

    def prefs_open(self, oid):
        menus = {"datetime": ("Date & time", self.dt_items, self.dt_pick),
                 "notify": ("Notifications", self.nt_items, self.nt_pick),
                 "footer": ("Footer", self.ft_items, self.ft_pick),
                 "theme": ("Theme accent", self.th_items, self.th_pick)}
        self.push_screen(self.MenuCls(*menus[oid]))

    # ----- date & time -----
    def dt_items(self):
        time.tzset()
        ntp = ntp_on()
        return [heading(time.strftime("%A %d %B %Y   %H:%M:%S")), heading(""),
                item("tz", "\uf0ac", "Time zone", tz(), CYAN),
                item("ntp", "\uf021", "Automatic time",
                     ("on, synced" if ntp_synced() else "on, syncing") if ntp else "off", GREEN),
                item("clock", "\uf017", "Header clock", "24-hour" if military() else "12-hour", PINK)]

    def dt_pick(self, menu, oid):
        if oid == "tz":
            self.push_screen(self.MenuCls("Time zone", self.region_items, self.region_pick))
        elif oid == "ntp":
            ok, msg = run(["timedatectl", "set-ntp", "false" if ntp_on() else "true"])
            if not ok:
                self.notify(f"Could not change automatic time: {msg[:70]}", severity="error")
        elif oid == "clock":
            val = "false" if military() else "true"
            fmt = "%a %d %b %H:%M" if val == "true" else "%a %d %b %I:%M %p"
            tmux_conf_set(r"^set -g @dracula-military-time .*$", f"set -g @dracula-military-time {val}")
            tmux_conf_set(r"^set -g @dracula-time-format .*$", f"set -g @dracula-time-format '{fmt}'")
            sh(f"tmux source-file {TMUX_CONF}")

    def region_items(self):
        self._zones = sh("timedatectl list-timezones").splitlines()
        cur = tz()
        regions = sorted({z.split("/")[0] for z in self._zones if "/" in z})
        opts = [item(f"reg:{r}", "\uf0ac", r,
                     DOT + "current" if cur.startswith(r + "/") else
                     f"{sum(1 for z in self._zones if z.startswith(r + '/'))} zones", CYAN) for r in regions]
        opts.append(item("tz:UTC", "\uf0ac", "UTC", DOT + "current" if cur == "UTC" else "", CYAN))
        return opts

    def region_pick(self, menu, oid):
        if oid.startswith("reg:"):
            r = oid[4:]
            self.push_screen(self.MenuCls(r, lambda: self.zone_items(r), self.zone_pick))
        elif oid.startswith("tz:"):
            self.set_zone(oid[3:], 1)

    def zone_items(self, region):
        cur = tz()
        return [item(f"tz:{z}", "\uf017", z[len(region) + 1:].replace("_", " ")[:24],
                     DOT + "current" if z == cur else "", CYAN)
                for z in self._zones if z.startswith(region + "/")]

    def zone_pick(self, menu, oid):
        if oid.startswith("tz:"):
            self.set_zone(oid[3:], 2)

    def set_zone(self, zone, pops):
        ok, msg = run(["timedatectl", "set-timezone", zone])
        if ok:
            for _ in range(pops):
                self.pop_screen()
            self.notify(f"Time zone set to {zone}. The header clock follows after the next restart.")
        else:
            self.notify(f"Could not set time zone: {msg[:70]}", severity="error")

    # ----- notifications -----
    def nt_items(self):
        opts = [item(f"flag:{n}", icon, label, onoff(not flag(n), desc), PINK)
                for n, icon, label, desc in NOTIFY_FLAGS]
        watch = sh("systemctl --user is-enabled deck-watch.timer") == "enabled"
        opts.append(item("watch", "\uf071", "System warnings", onoff(watch, "heat, disk, power"), ORANGE))
        opts += [heading(""),
                 item("test", "\uf0f3", "Send a test", "", CYAN),
                 item("recent", "\uf1da", "Recent notifications", "last 20", PURPLE)]
        return opts

    def nt_pick(self, menu, oid):
        if oid.startswith("flag:"):
            set_flag(oid[5:], not flag(oid[5:]))
        elif oid == "watch":
            on = sh("systemctl --user is-enabled deck-watch.timer") == "enabled"
            run(["systemctl", "--user", "disable" if on else "enable", "--now", "deck-watch.timer"])
        elif oid == "test":
            subprocess.Popen([f"{HOME}/bin/notify", "-s", "Test notification from settings"])
        elif oid == "recent":
            self.push_screen(self.MenuCls("Recent notifications", self.recent_items, lambda m, o: None))

    def recent_items(self):
        try:
            lines = open(NOTIFY_LOG).read().splitlines()[-20:][::-1]
        except FileNotFoundError:
            lines = []
        return [heading(l[:100]) for l in lines] or [heading("No notifications yet")]

    # ----- footer -----
    def ft_items(self):
        hidden = footer_hidden()
        opts = [item("show", "\uf0db", "Show footer", onoff(footer_shown()), GREEN), heading(""), heading("Blocks")]
        opts += [item(f"blk:{k}", icon, label, onoff(k not in hidden, desc), CYAN)
                 for k, icon, label, desc in FOOTER_BLOCKS]
        return opts

    def ft_pick(self, menu, oid):
        if oid == "show":
            new = "off" if footer_shown() else "bottom"
            sh(f"tmux set -g pane-border-status {new}")
            tmux_conf_set(r"^set -g pane-border-status .*$", f"set -g pane-border-status {new}")
        elif oid.startswith("blk:"):
            names = footer_hidden() ^ {oid[4:]}
            save_footer_hidden(names)
            sh("tmux refresh-client -S")

    # ----- theme -----
    def th_items(self):
        cur = current_accent()
        return [heading("Menus, active tab, selections and the terminal cursor"), heading("")] + \
               [item(f"acc:{c}", "\uf111", name, DOT + "current" if c == cur else "", c) for name, c in ACCENTS]

    def th_pick(self, menu, oid):
        if not oid.startswith("acc:") or oid[4:] == current_accent():
            return
        color = oid[4:]
        p = load_prefs()
        p["accent"] = color
        save_prefs(p)
        write_accent_tmux(color)
        set_foot_cursor(color)
        sh("tmux respawn-window -k -t deck:apps \"sh -c '~/bin/launcher.py; exec bash'\"")
        self.notify("Applying accent color: restarting the display...")
        self.set_timer(1.5, swaymsg_exit)
        self.set_timer(3.0, lambda: subprocess.Popen(
            ["tmux", "respawn-window", "-k", "-t", "deck:settings", "sh -c '~/bin/settings.py; exec bash'"]))
